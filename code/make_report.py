"""Generate report.md -> report.html -> report.pdf from results."""

import json
import subprocess
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).parent / "src"))
from el2n_nlp import config  # noqa: E402


def main():
    summary = json.load(open(config.RESULTS_DIR / "summary.json"))
    stats = json.load(open(config.SUBSETS_DIR / "stats.json"))
    examples = json.load(open(config.RESULTS_DIR / "top_examples.json"))

    from scipy.stats import spearmanr

    runs = sorted(config.RUNS_DIR.glob("*.json"))
    total_wall = sum(json.load(open(f))["wall_time_s"] for f in runs)

    score_runs = [np.load(p) for p in sorted(config.SCORES_DIR.glob("scores_seed*.npy"))
              if not p.stem.endswith("_early")]
    rhos = [
        spearmanr(score_runs[i], score_runs[j]).statistic
        for i in range(len(score_runs))
        for j in range(i + 1, len(score_runs))
    ]

    def g(mode, pct):
        return summary.get(f"{mode}_{pct}")

    def acc(mode, pct):
        s = g(mode, pct)
        return f"{s['final_mean'] * 100:.2f} ± {s['final_std'] * 100:.2f}" if s else "—"

    def accs(mode, pct):
        s = g(mode, pct)
        return ", ".join(f"{a * 100:.2f}" for a in s["accs"]) if s else "—"

    full = g("full", 100)
    rows = ""
    for p in config.SIZES_PCT:
        e, r = g("el2n", p), g("random", p)
        diff = (e["final_mean"] - r["final_mean"]) * 100 if e and r else float("nan")
        rows += f"| {p}% | {acc('el2n', p)} | {acc('random', p)} | {diff:+.2f} |\n"

    hi = examples["highest"]
    ex_rows = ""
    for cls in config.CLASS_NAMES[:3]:
        e = hi[cls][0]
        text = e["text"][:150].replace("|", "\\|")
        ex_rows += f"| {cls} | {e['score']:.3f} | {text}… |\n"

    n_runs = len(runs)
    bal50 = stats["el2n_subsets"]["50pct"]["class_counts"]

    md = MD_TEMPLATE
    for k, v in {
        "FULL": acc("full", 100),
        "FULL_ACCS": accs("full", 100),
        "E10": acc("el2n", 10), "R10": acc("random", 10),
        "E25": acc("el2n", 25), "R25": acc("random", 25),
        "E50": acc("el2n", 50), "R50": acc("random", 50),
        "E75": acc("el2n", 75), "R75": acc("random", 75),
        "TABLE_ROWS": rows.strip(),
        "RHO": f"{np.mean(rhos):.3f}",
        "RHO_MIN": f"{np.min(rhos):.3f}",
        "RHO_MAX": f"{np.max(rhos):.3f}",
        "N_RUNS": str(n_runs),
        "TOTAL_HOURS": f"{total_wall / 3600:.1f}",
        "EX_ROWS": ex_rows.strip(),
        "BAL50": ", ".join(f"{c / sum(bal50) * 100:.1f}%" for c in bal50),
        "BAL10": ", ".join(
            f"{c / sum(stats['el2n_subsets']['10pct']['class_counts']) * 100:.1f}%"
            for c in stats["el2n_subsets"]["10pct"]["class_counts"]
        ),
    }.items():
        md = md.replace("{{" + k + "}}", v)

    report_dir = config.ROOT / "report"
    report_dir.mkdir(exist_ok=True)
    md_path = report_dir / "report.md"
    md_path.write_text(md)

    import markdown as mdlib

    html_body = mdlib.markdown(md, extensions=["tables", "fenced_code"])
    html = HTML_SHELL.replace("{{BODY}}", html_body)
    html_path = report_dir / "report.html"
    html_path.write_text(html)

    subprocess.run(
        [
            "chromium", "--headless", "--disable-gpu", "--no-sandbox",
            "--print-to-pdf=" + str(report_dir / "report.pdf"),
            "--no-pdf-header-footer", str(html_path),
        ],
        check=True,
    )
    print("report written:", md_path, "+ report.pdf")


